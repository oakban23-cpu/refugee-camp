import asyncio, sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from h import *
async def main():
    p = start_server()
    async with async_playwright() as pw:
        b = await pw.chromium.launch()
        A = await new_client(b, 'Alpha', 'mage'); B = await new_client(b, 'Bravo', 'mage')
        for c in (A,B): await c.ev("()=>{ov.hidden=true;enterMap(4,{x:1500,y:1500});}")
        await A.wait(3000)
        H,O=(A,B) if await A.ev("()=>isHost()") else (B,A)
        print('props', await H.ev("()=>[PRP.b.length,PRP.g.length]"), await O.ev("()=>[PRP.b.length,PRP.g.length,PRP.b[0].x===undefined]"))
        bx=await H.ev("()=>[PRP.b[0].x,PRP.b[0].y]")
        for c in (H,O): await c.ev(f"()=>{{me.x={bx[0]}-90;me.y={bx[1]}}}")
        await H.wait(1500)
        await H.ev(f"()=>{{const x={bx[0]}+10,y={bx[1]},hp=1e7;const m={{id:++mid,x,y,tx:x,ty:y,t:0,L:20,p:1,hx:x,hy:y,hp,mh:hp,tg:null,tt:0,ac:99,w:null,lg:0,elb:1,tzb:1,shb:1,szb:1,root:99}};mons.push(m);window._m=m.id}}")
        await H.wait(1500); mid=await H.ev("()=>window._m")
        print('O sees mon', await O.ev(f"()=>{{const m=mons.find(q=>q.id==={mid});return m?Math.round(m.mh-m.hp):null}}"))
        await O.ev(f"()=>{{const m=mons.find(q=>q.id==={mid});addHit(m,10,0,1,'melee')}}")
        await H.wait(1500)
        print('H barrel dead', await H.ev("()=>PRP.b[0].dead>performance.now()"), 'H mon dmg', await H.ev(f"()=>{{const m=mons.find(q=>q.id==={mid});return m?Math.round(m.mh-m.hp):null}}"),'O pd',await O.ev("()=>Math.round(pd())"))
        gi=await O.ev("()=>{const n=performance.now();const i=PRP.g.findIndex(q=>q.burn<=n&&q.ash<=n);const q=PRP.g[i];me.x=q.x-60;me.y=q.y;return i}")
        await O.ev(f"()=>{{const q=PRP.g[{gi}];propsIgniteNear(q.x,q.y,1,uid)}}");await H.wait(1200)
        print('H grass burn', await H.ev(f"()=>PRP.g[{gi}].burn>performance.now()"))
        sh=await H.ev("()=>{const s=PRP.sh[0];me.x=s.x;me.y=s.y+30;return [s.x,s.y]}")
        await O.ev(f"()=>{{me.x={sh[0]}+60;me.y={sh[1]}+40}}");await H.wait(1500)
        await H.ev("()=>shrineUse()");await H.wait(1200)
        print('shrine H',await H.ev("()=>me.shrB"),'O',await O.ev("()=>[me.shrB,PRP.sh[0].cd>performance.now()]"))
        tp=await H.ev("()=>{const t=PRP.s[0];me.x=t.x-80;me.y=t.y;return [t.x,t.y]}")
        await O.ev(f"()=>{{me.x={tp[0]}-60;me.y={tp[1]}}}");await H.wait(1500)
        await H.ev(f"()=>{{const x={tp[0]}+3,y={tp[1]},hp=1e6;mons.push({{id:++mid,x,y,tx:x,ty:y,t:0,L:20,p:1,hx:x,hy:y,hp,mh:hp,tg:null,tt:0,ac:99,w:null,lg:0,elb:1,tzb:1,shb:1,szb:1,root:99}})}}")
        await H.wait(1500)
        print('spike H', await H.ev("()=>PRP.s[0].cd>performance.now()"),'O',await O.ev("()=>PRP.s[0].cd>performance.now()"))
        for c in (A,B):print(c.name,[e for e in c.errs if 'TUNNEL' not in e][:3])
        await b.close()
    p.terminate()
asyncio.run(main())
