import asyncio, sys, random
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from h import *
async def main():
    p = start_server()
    async with async_playwright() as pw:
        b = await pw.chromium.launch()
        A = await new_client(b, 'Ra'+str(random.randint(1000,9999)), 'archer', 99)
        B = await new_client(b, 'Rb'+str(random.randint(1000,9999)), 'mage', 40)
        print('A',await A.ev("()=>[me.lv,curMap,me.cls2,clsName()]"))
        await A.ev("()=>{gmGod=true;me.cls2=1;me.brU={1:1,2:1};me.br=2;applyBr();applyBr();recalc();me.ast=me.ast||{n:0,p:{}};me.ptx={12:500};me.x=1790;me.y=1700}")
        for i in range(3): await A.ev("()=>rbShardDrop(true)")
        print('shards after 3 drops',await A.ev("()=>rbSt().sh"))
        await A.ev("()=>{rbShard(5,'test');me.gold=1500000}")
        await A.wait(600)
        print('btn',await A.ev("()=>{const b=$('rbb');return [b&&!b.hidden,b&&b.textContent]}"))
        await A.pg.click('#rbb');await A.wait(400)
        await A.pg.screenshot(path='rb_ui.png')
        await A.pg.click('[data-rba="go1"]');await A.wait(200)
        await A.pg.click('[data-rba="go2"]');await A.wait(1200)
        await A.pg.screenshot(path='rb_cin.png')
        await A.wait(2000)
        await A.pg.screenshot(path='rb_flash.png')
        await A.wait(1800)
        r=await A.ev("()=>[me.lv,me.xp,me.rb,me.cls2,pts(),spts(),me.gold,rbSt().sh,clsName(),JSON.stringify(me.rbC2)]")
        print('after rebirth',r)
        await A.wait(3000)
        print('B sees',await B.ev("()=>Object.values(others).map(o=>[o.n,o.lv,o.rb])"))
        # level up to 50
        out=await A.ev("()=>{const L=[];for(let i=0;i<60&&me.lv<55;i++){me.xp=need(me.lv);gainXP(me.x,me.y,1);if(me.lv===49||me.lv===50||me.lv===51)L.push([me.lv,me.cls2,me.br,spts()])}return [L,me.lv,clsName(),spts()]}")
        print('lv up',out)
        # roundtrip
        r=await A.ev("()=>{const c=cleanChar(JSON.parse(JSON.stringify(snap())));return JSON.stringify([c.rb,c.rbq,c.rbC2,c.ptx,c.lv,c.cls2,c.br,c.ab])}")
        print('clean',r)
        r=await A.ev("()=>{const s=snap();s.lv=30;s.cls2=0;const c=cleanChar(JSON.parse(JSON.stringify(s)));return JSON.stringify([c.lv,c.cls2,c.rbC2])}")
        print('clean lv30',r)
        r=await A.ev("()=>{me.ab={str:200,vit:0,int:0,agi:0,luk:0};const c=cleanChar(JSON.parse(JSON.stringify(snap())));return [me.lv,abSum(c.ab)]}")
        print('ab 4/lv kept',r)
        await A.ev("()=>{me.ab={str:0,vit:0,int:0,agi:0,luk:0};me.x=1790;me.y=1720}")
        await A.pg.add_style_tag(content='*{visibility:hidden!important} canvas{visibility:visible!important}')
        await A.wait(800)
        await A.pg.screenshot(path='rb_altar.png')
        print(A.errs[:3],B.errs[:3])
        await b.close()
    p.terminate()
asyncio.run(main())
